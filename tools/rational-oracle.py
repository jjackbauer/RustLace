#!/usr/bin/env python3
"""Independent rational-arithmetic oracle for RustLace (RNL-CI-006).

The oracle is Python's standard-library `fractions.Fraction`, which was written independently of
the Rust kernel. This script emits a checked-in TSV fixture; the Rust integration test
(`lovelace-rational/tests/oracle.rs`) reads the same file and compares every case. It never imports
or links the Rust code, so the fixture cannot agree with a bug simply by sharing an implementation.

Usage:
    python tools/rational-oracle.py --check    # fail when the fixture is stale
    python tools/rational-oracle.py --write    # regenerate the fixture
"""

from __future__ import annotations

import random
import sys
from fractions import Fraction
from pathlib import Path

SEED = 20261117
FIXTURE = Path("parity/rational/oracle.tsv")


def fraction_text(value: Fraction) -> str:
    """Canonical `numerator/denominator` text, with a positive denominator."""
    return f"{value.numerator}/{value.denominator}"


def parse_fraction(text: str) -> Fraction:
    numerator, denominator = text.split("/")
    return Fraction(int(numerator), int(denominator))


def cases() -> list[tuple[str, Fraction, Fraction, str]]:
    """The campaign: explicit regressions plus deterministic seeded arithmetic cases."""
    out: list[tuple[str, Fraction, Fraction, str]] = []

    def add(op: str, left: Fraction, right: Fraction) -> None:
        if op == "cmp":
            expected = "-1" if left < right else ("1" if left > right else "0")
        elif op == "add":
            expected = fraction_text(left + right)
        elif op == "sub":
            expected = fraction_text(left - right)
        elif op == "mul":
            expected = fraction_text(left * right)
        elif op == "div":
            expected = fraction_text(left / right)
        else:
            raise AssertionError(op)
        out.append((op, left, right, expected))

    # The mandatory signed-division regression and its sign siblings.
    add("div", Fraction(1, 2), Fraction(-1, 4))
    add("div", Fraction(-1, 2), Fraction(-1, 4))
    add("div", Fraction(-1, 2), Fraction(1, 4))
    add("div", Fraction(1, 2), Fraction(1, 4))
    add("add", Fraction(0, 1), Fraction(0, 1))
    add("sub", Fraction(0, 1), Fraction(-3, 7))
    add("mul", Fraction(0, 1), Fraction(123456789, 987654321))
    add("div", Fraction(0, 1), Fraction(-5, 9))
    add("cmp", Fraction(-1, 2), Fraction(-1, 3))
    add("cmp", Fraction(2, 4), Fraction(1, 2))
    add("cmp", Fraction(1, 3), Fraction(1, 2))

    # A normalization that no u64-sized GCD can express.
    ten30 = 10**30
    add("add", Fraction(ten30 + 4, ten30 + 6), Fraction(1, 3))
    add("mul", Fraction(ten30 + 4, ten30 + 6), Fraction(ten30 + 6, ten30 + 4))

    rng = random.Random(SEED)
    for _ in range(240):
        left = Fraction(rng.randint(-10**6, 10**6), rng.randint(1, 60))
        right = Fraction(rng.randint(-10**6, 10**6), rng.randint(1, 60))
        if right == 0:
            right = Fraction(1, 1)
        add(rng.choice(["add", "sub", "mul"]), left, right)
        add("div", left, right)
        if rng.random() < 0.25:
            add("cmp", left, right)

    # Large operands: 200-bit numerators and denominators force arbitrary-precision reduction.
    for _ in range(60):
        left = Fraction(rng.getrandbits(200) + 1, rng.getrandbits(160) + 1)
        right = Fraction(rng.getrandbits(200) + 1, rng.getrandbits(160) + 1)
        if rng.random() < 0.5:
            left = -left
        if rng.random() < 0.5:
            right = -right
        add(rng.choice(["add", "sub", "mul"]), left, right)
        add("div", left, right)
        add("cmp", left, right)

    # Shared factors beyond u64: both operands are multiples of 2^100.
    shared = 2**100
    left = Fraction(2**200 + shared, 2**200 - shared)
    right = Fraction(2**200 - shared, 2**200 + shared)
    add("mul", left, right)
    add("div", left, right)
    return out


def render() -> str:
    lines = [
        "# RustLace rational oracle (generated by tools/rational-oracle.py).",
        "# Source of truth: Python standard-library fractions.Fraction, seed",
        f"# {SEED}. Format: op<TAB>left<TAB>right<TAB>expected.",
    ]
    for op, left, right, expected in cases():
        lines.append(f"{op}\t{fraction_text(left)}\t{fraction_text(right)}\t{expected}")
    return "\n".join(lines) + "\n"


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    target = root / FIXTURE
    generated = render()
    if "--write" in sys.argv:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generated, encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(root)} ({len(cases())} cases)")
        return 0
    if "--check" in sys.argv:
        if not target.exists():
            print(f"missing oracle fixture: {target}", file=sys.stderr)
            return 2
        current = target.read_text(encoding="utf-8")
        if current != generated:
            print(
                "rational oracle fixture is stale; run python tools/rational-oracle.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"rational oracle: {len(cases())} cases match the Python Fraction oracle")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
